CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker VARCHAR(16) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    cik VARCHAR(20) UNIQUE
);

CREATE TABLE insiders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    cik VARCHAR(20) UNIQUE
);

CREATE TABLE insider_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies (id),
    insider_id BIGINT NOT NULL REFERENCES insiders (id),
    transaction_date DATE NOT NULL,
    filing_date DATE,
    code VARCHAR(8) NOT NULL,
    acquired_or_disposed VARCHAR(8) NOT NULL,
    shares NUMERIC(18, 4) NOT NULL,
    price_per_share NUMERIC(18, 4),
    shares_owned_following NUMERIC(18, 4),
    security_title VARCHAR(120) NOT NULL,
    insider_role VARCHAR(120)
);

CREATE INDEX insider_transactions_date_idx ON insider_transactions (transaction_date DESC, id DESC);
CREATE INDEX insider_transactions_company_idx ON insider_transactions (company_id);
CREATE INDEX insider_transactions_insider_idx ON insider_transactions (insider_id);
